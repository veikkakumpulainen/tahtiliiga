// Regenerates src/lib/legalContent.ts from TERMS_OF_SERVICE.md and PRIVACY_POLICY.md.
// Run with: npm run sync-legal
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// The app renders section text as plain RN <Text> (single style, no inline
// rich text), so markdown emphasis markers would show up literally - strip them.
const stripEmphasis = (value) => value.replace(/\*\*(.+?)\*\*/g, "$1").replace(/(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)/g, "$1");

function parseMarkdown(filePath) {
  const raw = readFileSync(filePath, "utf8").replace(/\r\n/g, "\n").trim();
  const lines = raw.split("\n");
  let effectiveDate = "";
  const sections = [];
  let currentHeading = null;
  let currentLines = [];

  const flush = () => {
    if (currentHeading === null) return;
    const blocks = [];
    let block = [];
    for (const line of currentLines) {
      if (line.trim() === "") {
        if (block.length) { blocks.push(block); block = []; }
      } else {
        const bulleted = line.startsWith("- ") ? `• ${line.slice(2)}` : line;
        block.push(stripEmphasis(bulleted));
      }
    }
    if (block.length) blocks.push(block);
    const text = blocks.map((b) => b.join("\n")).join("\n\n");
    sections.push({ heading: currentHeading, text });
  };

  for (const line of lines) {
    const dateMatch = line.match(/^\*\*Voimassa:\s*(.+?)\*\*$/);
    if (dateMatch) { effectiveDate = `Voimassa: ${dateMatch[1]}`; continue; }
    const headingMatch = line.match(/^##\s+(.+)$/);
    if (headingMatch) {
      flush();
      currentHeading = stripEmphasis(headingMatch[1].trim());
      currentLines = [];
      continue;
    }
    if (line.match(/^#\s+/)) continue; // top-level title, not a section
    if (currentHeading !== null) currentLines.push(line);
  }
  flush();
  return { effectiveDate, sections };
}

const terms = parseMarkdown(path.join(root, "TERMS_OF_SERVICE.md"));
const privacy = parseMarkdown(path.join(root, "PRIVACY_POLICY.md"));

const esc = (value) => value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

function renderSections(sections) {
  return sections.map((section) => `  {\n    heading: \`${esc(section.heading)}\`,\n    text: \`${esc(section.text)}\`,\n  },`).join("\n");
}

const output = `// Generated by scripts/generate-legal-content.mjs from TERMS_OF_SERVICE.md and PRIVACY_POLICY.md.
// Edit those markdown files and run \`npm run sync-legal\` to regenerate this file - do not edit it directly.

export type LegalSection = { heading: string; text: string };

export const legalEffectiveDate = "${terms.effectiveDate}";

export const termsSections: LegalSection[] = [
${renderSections(terms.sections)}
];

export const privacySections: LegalSection[] = [
${renderSections(privacy.sections)}
];
`;

writeFileSync(path.join(root, "src", "lib", "legalContent.ts"), output, "utf8");
console.log("Wrote src/lib/legalContent.ts from TERMS_OF_SERVICE.md and PRIVACY_POLICY.md.");
